#!/usr/bin/env node
/**
 * gen-springs.mjs
 *
 * Generates CSS linear() easing strings and settle durations for the five
 * ultrapolish spring tokens, solved by Motion's own spring so CSS and
 * `motion/react` animations share one physics.
 *
 * Rename: nothing required. Change TOKENS only if the project's design
 * contract names different springs. This file carries no palette or typeface.
 *
 * Usage:
 *   npm i -D motion            (or pnpm add -D motion)
 *   node gen-springs.mjs       prints CSS custom properties, paste into motion.css
 *   node gen-springs.mjs --json  prints the same as JSON
 *
 * Do not hand-edit the generated linear() strings; re-run this.
 * Requires Node 20+.
 */

import { spring } from 'motion';

const TOKENS = {
  micro:  { visualDuration: 0.20, bounce: 0.12 },
  snappy: { visualDuration: 0.30, bounce: 0.18 },
  smooth: { visualDuration: 0.40, bounce: 0.00 },
  bouncy: { visualDuration: 0.35, bounce: 0.32 },
  gentle: { visualDuration: 0.60, bounce: 0.00 },
};

const POINTS = 60;          // 61 samples, 0..1 inclusive
const SAMPLE_MS = 1000 / 240;
const MAX_MS = 4000;

function solve(name, cfg) {
  const gen = spring({ ...cfg, keyframes: [0, 1] });

  // Settle time: the first sample where Motion reports done.
  let settle = 0;
  for (let t = 0; t < MAX_MS; t += SAMPLE_MS) {
    if (gen.next(t).done) { settle = t; break; }
  }
  if (!settle) settle = 1000;

  const pts = [];
  for (let i = 0; i <= POINTS; i++) {
    const { value } = gen.next((i / POINTS) * settle);
    pts.push(Number(value.toFixed(4)));
  }
  pts[0] = 0;
  pts[POINTS] = 1;

  return {
    name,
    visualDuration: cfg.visualDuration,
    bounce: cfg.bounce,
    settleMs: Math.round(settle),
    linear: `linear(${pts.join(', ')})`,
  };
}

const results = Object.entries(TOKENS).map(([name, cfg]) => solve(name, cfg));

if (process.argv.includes('--json')) {
  console.log(JSON.stringify(results, null, 2));
} else {
  console.log('/* Generated by gen-springs.mjs. Do not hand-edit; re-run the script. */');
  console.log(':root {');
  for (const r of results) {
    console.log(`  /* ${r.name}: visualDuration ${r.visualDuration}s, bounce ${r.bounce} */`);
    console.log(`  --ease-${r.name}: ${r.linear};`);
    console.log(`  --dur-spring-${r.name}: ${r.settleMs}ms;`);
  }
  console.log('}');
}
